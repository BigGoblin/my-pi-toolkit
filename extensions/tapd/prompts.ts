export function buildUnderstandPrompt(opts: {
  title: string;
  storyId: string;
  url: string;
  description: string;
  projectPaths: string[];
  understandingFile: string;
}): string {
  const pathBlock = opts.projectPaths.length > 0
    ? opts.projectPaths.map((path) => `- ${path}`).join("\n")
    : "- （未指定，请在当前工作目录中查找相关代码）";
  const description = opts.description.trim() || "（无描述）";
  return [
    "以下为 TAPD 需求上下文，供后续需求理解使用。",
    "",
    "## 需求",
    `标题：${opts.title}`,
    `链接：${opts.url}`,
    `ID：${opts.storyId}`,
    "",
    "## 需求描述",
    description,
    "",
    "## 相关项目路径",
    pathBlock,
    "",
    "## 理解文档输出路径",
    opts.understandingFile,
  ].join("\n");
}

